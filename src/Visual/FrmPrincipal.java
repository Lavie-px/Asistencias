    public void configurarPorRol(String tipoUsuario) {
        tipoUsuario = tipoUsuario.toLowerCase();

        switch (tipoUsuario) {
            case "1":
                BtnEntrada.setVisible(true);
                BtnSalida.setVisible(true);
                BtnAtrasos.setVisible(true);
                
            case "0":
                BtnEntrada.setVisible(true);
                BtnSalida.setVisible(true);
                BtnAtrasos.setVisible(false);
                
            default:
                JOptionPane.showMessageDialog(this, "Tipo de usuario no reconocido");
                System.exit(0);
                break;
        }
    }

    private void BtnEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEntradaActionPerformed
        try {
            boolean ok = asistenciaCtrl.marcarEntrada(Sesion.getRut());
            if (ok) {
                LblMensaje.setForeground(new Color(0, 128, 0));
                LblMensaje.setText("Entrada marcada correctamente");
            } else {
                LblMensaje.setForeground(Color.red);
                LblMensaje.setText("Ya registraste tu entrada hoy");
            }
        } catch (Exception e) {
            LblMensaje.setForeground(Color.red);
            LblMensaje.setText("Error: no hay conexión con la base de datos");
        }
    }//GEN-LAST:event_BtnEntradaActionPerformed

