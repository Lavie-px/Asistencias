    private void cargarDirectiva() {
        String[] datos = horarioController.obtenerDirectiva();

        if (datos[0] != null) {
            FTxtEntrada.setText(datos[0]);
        } else {
            FTxtEntrada.setText("");
        }

        if (datos[1] != null) {
            FTxtSalida.setText(datos[1]);
        } else {
            FTxtSalida.setText("");
        }
    }

