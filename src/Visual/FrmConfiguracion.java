    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
        String horaEntrada = FTxtEntrada.getText().trim();
        String horaSalida = FTxtSalida.getText().trim();

        // Validar entrada
        if (!horaEntrada.isEmpty()
                && !horaEntrada.matches("([01]\\d|2[0-3]):[0-5]\\d")) {

            JOptionPane.showMessageDialog(this,"La hora de entrada no es válida.","Error",JOptionPane.ERROR_MESSAGE);

            return;
        }

        // Validar salida
        if (!horaSalida.isEmpty()
                && !horaSalida.matches("([01]\\d|2[0-3]):[0-5]\\d")) {

            JOptionPane.showMessageDialog( this,"La hora de salida no es válida.","Error",JOptionPane.ERROR_MESSAGE);

            return;
        }

        boolean guardado = horarioController.guardarHorario(horaEntrada,horaSalida);

        if (guardado) {

            JOptionPane.showMessageDialog(this,"Horario guardado correctamente.","Configuración",JOptionPane.INFORMATION_MESSAGE);

        } else {

            JOptionPane.showMessageDialog(this,"No se pudo guardar el horario.","Error",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BtnGuardarActionPerformed

